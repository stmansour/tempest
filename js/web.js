/**
 * web.js - Authentic Atari Tempest Parametric Web Geometry
 * 
 * Recreates the exact 16 web configurations, world coordinates,
 * and 3D perspective projections extracted directly from Dave Theurer's
 * original Atari 6502 assembly source:
 *  /  (lines 1230-1385) , , , , , , .
 */

export class Web {
  constructor(id, name, outerRim, innerHole, isClosed = true, strokeColor = '#00ffff') {
    this.id = id;
    this.name = name;
    this.outerRim = outerRim; // Array of {x, y} in world units [-85.1, +85.1]
    this.innerHole = innerHole; // Array of {x, y} in world units at abyss spawn (z=0)
    this.isClosed = isClosed;
    this.strokeColor = strokeColor;
    this.vertexCount = outerRim.length;
    this.laneCount = isClosed ? this.vertexCount : this.vertexCount - 1;
  }

  /**
   * Returns vertex position at depth z (0.0 = hole abyss, 1.0 = outer rim)
   * Uses authentic non-linear perspective depth curve
   */
  getVertexPos(vIndex, z) {
    const idx = ((vIndex % this.vertexCount) + this.vertexCount) % this.vertexCount;
    const inner = this.innerHole[idx];
    const outer = this.outerRim[idx];
    
    // Authentic Atari perspective depth interpolation
    const t = Math.max(0, Math.min(1, z));
    const persp = Math.pow(t, 1.55);

    return {
      x: inner.x + (outer.x - inner.x) * persp,
      y: inner.y + (outer.y - inner.y) * persp
    };
  }

  getLaneIndices(laneIndex) {
    let idx = laneIndex;
    if (this.isClosed) {
      idx = ((idx % this.laneCount) + this.laneCount) % this.laneCount;
      return [idx, (idx + 1) % this.vertexCount];
    } else {
      idx = Math.max(0, Math.min(this.laneCount - 1, idx));
      return [idx, idx + 1];
    }
  }

  getLaneEdges(laneIndex, z) {
    const [vLeft, vRight] = this.getLaneIndices(laneIndex);
    return {
      left: this.getVertexPos(vLeft, z),
      right: this.getVertexPos(vRight, z)
    };
  }

  getLaneCenter(laneIndex, z) {
    const edges = this.getLaneEdges(laneIndex, z);
    return {
      x: (edges.left.x + edges.right.x) * 0.5,
      y: (edges.left.y + edges.right.y) * 0.5
    };
  }

  clampLane(laneIndex) {
    if (this.isClosed) {
      return ((laneIndex % this.laneCount) + this.laneCount) % this.laneCount;
    }
    return Math.max(0, Math.min(this.laneCount - 1, laneIndex));
  }
}

